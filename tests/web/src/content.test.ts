import { describe, expect, it } from "vitest";
import * as fs from "node:fs";
import * as path from "node:path";

// The template's own content, ported as it was: the tutorial under
// content/docs (sidebar generated from the folders, ordered by their
// _category_.json and each page's sidebar_position), the blog under
// content/blog, the home page and a Markdown page under src/pages.
const appDir = path.resolve(__dirname, "../../../apps/web");
const docsDir = path.join(appDir, "content/docs");
const blogDir = path.join(appDir, "content/blog");

function listPages(dir: string, prefix = ""): string[] {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      if (entry.isDirectory()) return listPages(path.join(dir, entry.name), `${prefix}${entry.name}/`);
      return /\.mdx?$/.test(entry.name) ? [`${prefix}${entry.name.replace(/\.mdx?$/, "")}`] : [];
    })
    .sort();
}

describe("the docs (apps/web/content/docs)", () => {
  it("holds exactly the template's tutorial", () => {
    expect(listPages(docsDir)).toEqual([
      "intro",
      "tutorial-basics/congratulations",
      "tutorial-basics/create-a-blog-post",
      "tutorial-basics/create-a-document",
      "tutorial-basics/create-a-page",
      "tutorial-basics/deploy-your-site",
      "tutorial-basics/markdown-features",
      "tutorial-extras/manage-docs-versions",
      "tutorial-extras/translate-your-site",
    ]);
  });

  it("keeps the template's text", () => {
    const intro = fs.readFileSync(path.join(docsDir, "intro.md"), "utf8");
    expect(intro).toContain("# Tutorial Intro");
    expect(intro).toContain("Let's discover **Docusaurus in less than 5 minutes**.");
  });

  it("orders the generated sidebar's two categories", () => {
    const category = (d: string) =>
      JSON.parse(fs.readFileSync(path.join(docsDir, d, "_category_.json"), "utf8")) as { label: string; position: number };
    expect(category("tutorial-basics")).toMatchObject({ label: "Tutorial - Basics", position: 2 });
    expect(category("tutorial-extras")).toMatchObject({ label: "Tutorial - Extras", position: 3 });
  });

  it("generates the sidebar from the folders, as the template did", async () => {
    const { default: sidebars } = (await import("@/sidebars.js")) as { default: Record<string, unknown> };
    expect(sidebars).toEqual({ tutorialSidebar: [{ type: "autogenerated", dirName: "." }] });
  });
});

describe("the blog (apps/web/content/blog)", () => {
  it("holds the template's four posts and its authors", () => {
    expect(listPages(blogDir)).toEqual([
      "2019-05-28-first-blog-post",
      "2019-05-29-long-blog-post",
      "2021-08-01-mdx-blog-post",
      "2021-08-26-welcome/index",
    ]);
    expect(fs.existsSync(path.join(blogDir, "authors.yml"))).toBe(true);
  });
});

describe("the component's own pages stay out of the site", () => {
  it("keeps the docs and the blog under content/, not docs/", async () => {
    const [[, options]] = (await import("@/docusaurus.config.js")).default.presets as [
      [string, { docs: { path: string }; blog: { path: string } }],
    ];
    expect(options.docs.path).toBe("content/docs");
    expect(options.blog.path).toBe("content/blog");
    // apps/web/docs/ is this component's catalog pages (overview, architecture,
    // runbook): generated, and not a page of the site.
    expect(fs.readdirSync(path.join(appDir, "docs")).sort()).toEqual(["architecture.md", "overview.md", "runbook.md"]);
  });
});
